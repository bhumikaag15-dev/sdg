// Generates supabase/seed_pathways.sql from the TS catalogue (single source of truth).
// Run: npx esbuild src/data/expandedPathways.ts --bundle --format=esm --outfile=.tmp.mjs && node scripts/gen-seed.mjs
import { writeFileSync, unlinkSync } from "node:fs";
const { expandedPathways } = await import("../.tmp.mjs");
const q = s => `'${String(s).replace(/'/g, "''")}'`;
const arr = a => `array[${a.map(q).join(",")}]::text[]`;
const rows = expandedPathways.map(p =>
  `(${[p.id,p.title,p.field,p.qualification,p.summary,p.duration,p.typical_entry].map(q).join(",")},${arr(p.study_topics)},${arr(p.job_roles)},${arr(p.industries)},${arr(p.next_steps)},${q(p.eligibility_note)},${q(p.demand_note)},${arr(p.source_urls)})`);
writeFileSync("supabase/seed_pathways.sql",
`-- AUTO-GENERATED by scripts/gen-seed.mjs (${rows.length} pathways). Run after schema.sql + migrations/002_core.sql.
insert into public.pathways (id,title,field,qualification,summary,duration,typical_entry,study_topics,job_roles,industries,next_steps,eligibility_note,demand_note,source_urls) values
${rows.join(",\n")}
on conflict (id) do update set title=excluded.title, field=excluded.field, qualification=excluded.qualification, summary=excluded.summary, duration=excluded.duration, typical_entry=excluded.typical_entry, study_topics=excluded.study_topics, job_roles=excluded.job_roles, industries=excluded.industries, next_steps=excluded.next_steps, eligibility_note=excluded.eligibility_note, demand_note=excluded.demand_note, source_urls=excluded.source_urls;
`);
unlinkSync(".tmp.mjs");
console.log(rows.length, "rows");
